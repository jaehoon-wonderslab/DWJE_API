-- =====================================================================================
--  [검토 요청 2] 1공장 프레스 기계별 수율 · 불량률
--
--  묻는 것 : 2026-08-01 ~ 2026-08-30 사이에
--            1공장(M-1공장) 프레스 작업장의 기계마다
--            수율과 불량률이 얼마였는지
--
--  ── 계산식 ────────────────────────────────────────────────────────────────────────
--      총생산 = 양품 + 불량
--      불량률 = 불량 ÷ 총생산 × 100
--      수율   = 양품 ÷ 총생산 × 100
--
--  ── 작업자 검토 요청 사항 (아래 6가지를 봐주세요) ─────────────────────────────────
--
--  (1) ★ 가장 중요 ★
--      위 계산식대로면 "수율 + 불량률 = 100" 이 항상 성립합니다.
--      즉 수율은 불량률의 뒤집은 값일 뿐, 별도 정보를 주지 않습니다.
--      현장에서 쓰는 수율이 이 뜻이 맞습니까?
--      혹시 수율을 아래처럼 다르게 계산한다면 알려주세요. 쿼리를 바꾸겠습니다.
--        - 투입 자재 대비 완성품 비율
--        - 목표 수량 대비 실적 비율
--        - 후공정 합격분까지 반영한 최종 수율
--
--  (2) 기계별 불량률을 낼 때 기간 전체를 한 번에 합산했습니다(총불량 ÷ 총생산).
--      날짜별 불량률을 구한 뒤 평균 내는 방식과는 값이 다릅니다.
--      어느 쪽이 현장 기준입니까?
--
--  (3) 8월에 실적이 없는 기계 5대는 수율·불량률을 계산할 수 없어 빈 값으로 둡니다.
--      0% 로 표시하면 "불량이 하나도 없었다" 로 오해될 수 있어 일부러 비웠습니다.
--
--  (4) 생산 개수가 적은 기계는 불량률이 크게 흔들립니다.
--      참고하시라고 총생산개수를 같이 넣었습니다.
--      "몇 개 미만은 제외" 같은 기준이 있으면 알려주세요.
--
--  (5) 취소·삭제 처리된 실적(del_flg='Y')은 제외했습니다. 맞습니까?
--
--  (6) 맨 아래 합계 행은 기계별 수율의 평균이 아니라
--      1공장 프레스 전체를 하나로 본 값입니다(전체 불량 ÷ 전체 생산).
--      기계마다 생산량이 달라서 단순 평균을 내면 왜곡되기 때문입니다.
--
--  ※ 기간은 8/1 00:00 부터 8/30 하루 전체를 포함합니다(8/31 00:00 직전까지).
--  ※ 조회만 하는 쿼리입니다. 데이터를 바꾸지 않습니다.
-- =====================================================================================

WITH
-- ── 조회 조건 : 이 부분만 바꾸면 기간과 작업장을 조정할 수 있습니다 ────────────────
조건 AS (
    SELECT 'PL01'::varchar                    AS 사업장,
           '2026-08-01 00:00:00'::timestamp   AS 시작,
           '2026-08-31 00:00:00'::timestamp   AS 종료_직전
),
-- ── 1공장 프레스 작업장 ────────────────────────────────────────────────────────────
--    공장 구분이 작업장 코드가 아니라 작업장 '이름' 에 들어 있어 이름으로 찾습니다.
대상작업장 AS (
    SELECT w.plant_cd, w.wc_cd, w.wc_nm
    FROM mes.tb_md_workcenter w, 조건 c
    WHERE w.plant_cd = c.사업장
      AND w.wc_nm LIKE '%프레스%'
      AND w.wc_nm LIKE '%M-1공장%'
      AND w.valid_from_dt <  c.종료_직전
      AND w.valid_to_dt   >= c.시작
),
-- ── 해당 작업장에 등록된 기계 (사용 중인 것만) ─────────────────────────────────────
대상기계 AS (
    SELECT t.wc_nm, e.plant_cd, e.eqpt_cd, e.eqpt_nm
    FROM 대상작업장 t
    INNER JOIN mes.tb_md_eqpt_by_workcenter ew
            ON ew.plant_cd = t.plant_cd AND ew.wc_cd = t.wc_cd
    INNER JOIN mes.tb_md_eqpt e
            ON e.plant_cd = ew.plant_cd AND e.eqpt_cd = ew.eqpt_cd
    WHERE e.use_flg = 'Y'
),
-- ── 기간 내 생산 실적을 기계 단위로 합산 ───────────────────────────────────────────
실적 AS (
    SELECT lh.eqpt_cd,
           sum(coalesce(lh.normal, 0))                           AS 양품개수,
           sum(coalesce(lh.defect, 0))                           AS 불량개수,
           sum(coalesce(lh.normal, 0) + coalesce(lh.defect, 0))  AS 총생산개수
    FROM mes.tb_pop_label_hist lh
    INNER JOIN 대상작업장 t ON t.plant_cd = lh.plant_cd AND t.wc_cd = lh.wc_cd
    CROSS JOIN 조건 c
    WHERE lh.del_flg   = 'N'          -- 취소·삭제분 제외
      AND lh.eqpt_cd IS NOT NULL      -- 기계가 찍히지 않은 실적 제외
      AND lh.ins_date >= c.시작
      AND lh.ins_date <  c.종료_직전
    GROUP BY lh.eqpt_cd
),
-- ── 기계별 결과 ────────────────────────────────────────────────────────────────────
기계별 AS (
    SELECT m.wc_nm,
           m.eqpt_cd,
           m.eqpt_nm,
           coalesce(r.총생산개수, 0) AS 총생산개수,
           coalesce(r.양품개수,   0) AS 양품개수,
           coalesce(r.불량개수,   0) AS 불량개수
    FROM 대상기계 m
    LEFT JOIN 실적 r ON r.eqpt_cd = m.eqpt_cd
),
-- ── 기계별 + 맨 아래 전체 합계 ─────────────────────────────────────────────────────
결과 AS (
    SELECT 0                AS 정렬구분,          -- 0 = 기계별, 1 = 합계
           wc_nm            AS 작업장,
           eqpt_cd          AS 기계코드,
           eqpt_nm          AS 기계명,
           총생산개수, 양품개수, 불량개수
    FROM 기계별
    UNION ALL
    -- 합계는 기계별 수율의 평균이 아니라, 전체를 하나로 본 값입니다.
    -- 기계마다 생산량이 달라 단순 평균을 내면 적게 만든 기계가 과대 반영됩니다.
    SELECT 1,
           max(wc_nm),
           '── 합계 ──',
           format('기계 %s대 중 %s대 가동',
                  count(*), count(*) FILTER (WHERE 총생산개수 > 0)),
           sum(총생산개수), sum(양품개수), sum(불량개수)
    FROM 기계별
)
SELECT
    작업장                                                        AS "작업장",
    기계코드                                                      AS "기계코드",
    기계명                                                        AS "기계명",
    총생산개수::bigint                                            AS "총생산개수",
    양품개수::bigint                                              AS "양품개수",
    불량개수::bigint                                              AS "불량개수",
    -- 생산이 0 인 기계는 계산할 수 없어 빈 값으로 둡니다 (0% 로 오해되지 않도록)
    round(100.0 * 양품개수 / nullif(총생산개수, 0), 2)             AS "수율(%)",
    round(100.0 * 불량개수 / nullif(총생산개수, 0), 2)             AS "불량률(%)"
FROM 결과
ORDER BY
    정렬구분,                                    -- 합계 행을 맨 아래로
    -- 불량률 높은 기계부터. 실적 없는 기계는 맨 뒤로 보냅니다.
    (총생산개수 = 0),
    불량개수::numeric / nullif(총생산개수, 0) DESC NULLS LAST,
    기계코드;
