COMMENT ON COLUMN ax.tb_prod_downtime.reason_cd        IS '비가동 사유 (DOWN_REASON 공통코드)';
COMMENT ON COLUMN ax.tb_prod_downtime.is_registered    IS '사유 등록 여부 — false 면 미등록(사유 미입력) 건';
COMMENT ON COLUMN ax.tb_prod_downtime.agent_reason_cd  IS 'Agent 가 제안한 사유 후보 (채택 전)';
COMMENT ON COLUMN ax.tb_prod_downtime.detected_by_cd   IS '감지 출처 — IOT / MES / MANUAL';

CREATE INDEX IF NOT EXISTS ix_tb_prod_downtime_eqpt ON ax.tb_prod_downtime (plant_cd, eqpt_cd, stop_at DESC);
CREATE INDEX IF NOT EXISTS ix_tb_prod_downtime_stop ON ax.tb_prod_downtime (stop_at DESC);

