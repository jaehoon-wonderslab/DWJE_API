CREATE TABLE IF NOT EXISTS ax.tb_prod_downtime (
    downtime_id     bigint          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_cd        common.d_plant_cd NOT NULL,
    eqpt_cd         common.d_eqpt_cd  NOT NULL,
    wc_cd           common.d_wc_cd,
    stop_at         timestamptz     NOT NULL,
    resume_at       timestamptz,
    elapsed_min     integer,
    reason_cd       varchar(30),
    remark          varchar(500),
    is_registered   boolean         NOT NULL DEFAULT false,
    detected_by_cd  varchar(30)     NOT NULL DEFAULT 'IOT',
    agent_reason_cd varchar(30),
    agent_confidence numeric(5,4),
    agent_basis     varchar(300),
    registered_at   timestamptz,
    registered_by   common.d_user_id,
    ins_date        timestamptz     NOT NULL DEFAULT now(),
    ins_user        common.d_user_id,
    upd_date        timestamptz     NOT NULL DEFAULT now(),
    upd_user        common.d_user_id,
    CONSTRAINT ck_tb_prod_downtime_period CHECK (resume_at IS NULL OR resume_at >= stop_at)
