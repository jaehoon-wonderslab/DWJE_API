/* 보고서 문서 (초안 → 임시저장 → 확정/반려) */
CREATE TABLE IF NOT EXISTS ax.tb_rpt_doc (
    doc_id              bigint          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_no              varchar(30),
    report_id           varchar(30)     REFERENCES ax.tb_rpt_report (report_id),
    form_id             integer         REFERENCES ax.tb_rpt_form (form_id),
    doc_kind_cd         varchar(30)     NOT NULL,
    title               varchar(200),
    target_date         date,
    period_from         timestamptz,
    period_to           timestamptz,
    occur_date          date,
    version_no          integer         NOT NULL DEFAULT 1,
    state_cd            varchar(30)     NOT NULL DEFAULT 'DRAFT',
    plant_cd            common.d_plant_cd,
    wc_cd               common.d_wc_cd,
    lot_no              common.d_lot_no,
    item_cd             common.d_item_cd,
    product_id          integer         REFERENCES ax.tb_prod_product (product_id),
    customer_id         integer         REFERENCES ax.tb_prod_customer (customer_id),
    disclosure_policy   varchar(200),
    correction_cnt      integer         NOT NULL DEFAULT 0,
    summary_json        jsonb,
    due_date            date,
    generated_at        timestamptz     NOT NULL DEFAULT now(),
    generated_by        common.d_user_id,
    confirmed_at        timestamptz,
    confirmed_by        common.d_user_id,
    rejected_at         timestamptz,
    rejected_by         common.d_user_id,
    reject_reason       varchar(500),
    remark              varchar(1000),
    del_flg             common.d_yn     NOT NULL DEFAULT 'N',
    ins_date            timestamptz     NOT NULL DEFAULT now(),
    ins_user            common.d_user_id,
    upd_date            timestamptz     NOT NULL DEFAULT now(),
    upd_user            common.d_user_id
);

COMMENT ON TABLE  ax.tb_rpt_doc              IS '보고서 문서 인스턴스 — 일일 생산현황·품질·폐기 보고서의 초안/버전/상태를 관리';
COMMENT ON COLUMN ax.tb_rpt_doc.doc_kind_cd  IS '문서 구분 (RPT_DOC_KIND) — DAILY / QUALITY / SCRAP';
COMMENT ON COLUMN ax.tb_rpt_doc.state_cd     IS '문서 상태 (RPT_DOC_STATE) — DRAFT / SAVED / CONFIRMED / REJECTED / PUBLISHED';
COMMENT ON COLUMN ax.tb_rpt_doc.doc_no       IS '화면 표기 문서번호 (폐기 보고서 등). 자동 채번';
COMMENT ON COLUMN ax.tb_rpt_doc.correction_cnt IS 'AI 초안 대비 사람이 보정한 항목 수';

CREATE INDEX IF NOT EXISTS ix_tb_rpt_doc_kind_date ON ax.tb_rpt_doc (doc_kind_cd, target_date DESC);
CREATE INDEX IF NOT EXISTS ix_tb_rpt_doc_state     ON ax.tb_rpt_doc (state_cd, generated_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_rpt_doc_no ON ax.tb_rpt_doc (doc_no) WHERE doc_no IS NOT NULL;

/* 보고서 항목 값 — 양식 항목(ax.tb_rpt_form_field) 단위 값과 기입 출처 */
CREATE TABLE IF NOT EXISTS ax.tb_rpt_doc_field (
    doc_id          bigint          NOT NULL REFERENCES ax.tb_rpt_doc (doc_id) ON DELETE CASCADE,
    field_seq       smallint        NOT NULL,
    section_cd      varchar(30)     NOT NULL DEFAULT 'BODY',
    field_nm        varchar(100)    NOT NULL,
    field_code      varchar(50),
    field_value     text,
    origin_cd       varchar(30)     NOT NULL DEFAULT 'MANUAL',
    is_corrected    boolean         NOT NULL DEFAULT false,
    blind_field_key varchar(30)     REFERENCES ax.tb_sys_data_field (field_key),
    remark          varchar(300),
    CONSTRAINT pk_tb_rpt_doc_field PRIMARY KEY (doc_id, field_seq)
);

COMMENT ON TABLE  ax.tb_rpt_doc_field           IS '보고서 항목 값 — 자동 기입/사람 보정 구분 포함';
COMMENT ON COLUMN ax.tb_rpt_doc_field.origin_cd IS '기입 출처 (RPT_ORIGIN) — MES / AI / MANUAL';
COMMENT ON COLUMN ax.tb_rpt_doc_field.section_cd IS '섹션 구분 — HEADER / RESULT / CONDITION / CAUSE / TRACE / ACTION / BODY';

/* 보고서 생성·처리 이력 */
CREATE TABLE IF NOT EXISTS ax.tb_rpt_doc_event (
    event_id        bigint          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id          bigint          NOT NULL REFERENCES ax.tb_rpt_doc (doc_id) ON DELETE CASCADE,
    event_at        timestamptz     NOT NULL DEFAULT now(),
    event_type_cd   varchar(30)     NOT NULL,
    detail          varchar(500),
    actor_user_id   common.d_user_id,
    actor_dept_nm   varchar(50)
);

COMMENT ON TABLE  ax.tb_rpt_doc_event                IS '보고서 생성·보정·확정·반려 이력';
COMMENT ON COLUMN ax.tb_rpt_doc_event.event_type_cd  IS '이벤트 (RPT_DOC_EVENT) — GENERATE / REGENERATE / CORRECT / SAVE / CONFIRM / REJECT / COPY / PUBLISH / EXPORT';

/* 증빙 이미지 첨부 */
CREATE TABLE IF NOT EXISTS ax.tb_rpt_doc_image (
    image_id        bigint          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_id          bigint          NOT NULL REFERENCES ax.tb_rpt_doc (doc_id) ON DELETE CASCADE,
    image_nm        varchar(200)    NOT NULL,
    nas_path        varchar(1000)   NOT NULL,
    defect_cd       common.d_defect_cd,
    lot_no          common.d_lot_no,
    captured_at     timestamptz,
    attached_at     timestamptz     NOT NULL DEFAULT now(),
    attached_by     common.d_user_id
);

COMMENT ON TABLE ax.tb_rpt_doc_image IS '품질 보고서 증빙 이미지 — NAS 경로 참조';

/* 검토 부서 · 결재선 */
CREATE TABLE IF NOT EXISTS ax.tb_rpt_doc_approval (
    doc_id          bigint          NOT NULL REFERENCES ax.tb_rpt_doc (doc_id) ON DELETE CASCADE,
    appr_seq        smallint        NOT NULL,
    step_cd         varchar(30)     NOT NULL,
    dept_id         integer         REFERENCES ax.tb_sys_dept (dept_id),
