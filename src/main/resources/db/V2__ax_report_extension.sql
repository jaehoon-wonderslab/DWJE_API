    state_cd        varchar(30)     NOT NULL DEFAULT 'WAITING',
    opinion         varchar(500),
    acted_at        timestamptz,
    due_date        date,
    CONSTRAINT pk_tb_rpt_doc_approval PRIMARY KEY (doc_id, appr_seq)
);

COMMENT ON TABLE  ax.tb_rpt_doc_approval          IS '보고서 검토 부서 · 결재선';
COMMENT ON COLUMN ax.tb_rpt_doc_approval.step_cd  IS '결재 단계 — DRAFT(기안) / REVIEW(검토) / APPROVE(승인)';
COMMENT ON COLUMN ax.tb_rpt_doc_approval.state_cd IS '처리 상태 — WAITING / DONE / REJECTED';

