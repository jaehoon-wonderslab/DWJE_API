-- =====================================================================================
--  덕우전자 AX 시스템 — 스키마 확장 (API 구현 전제)
--
--  배경
--  ----
--  기존 DDL(ai_db_query.sql / mes_db_query.sql / ai_db_vector_query.sql)에는
--  아래 업무를 담을 테이블이 정의되어 있지 않다.
--
--   1) 보고서 "문서 인스턴스"
--      ax.tb_rpt_report 는 보고서 '정의'(어떤 보고서가 있는지)만 담고 있어
--      일일 생산현황 보고(PR-03) · 품질 보고서(QC-03) · 폐기 보고서(RP-06/07)의
--      초안·버전·확정 상태·항목 값·결재선을 저장할 곳이 없다.
--   2) 비가동 이력 (PR-05)
--      설비 정지/재가동 구간과 사유를 담을 테이블이 없다.
--   3) 연간 출하계획 (RP-03)
--   4) 품목 단가 (RP-07 폐기 금액 산정)
--
--  본 스크립트는 위 4개 업무를 위한 최소 확장 테이블을 정의한다.
--  기존 테이블은 변경하지 않으며, 명명 규칙(tb_ 접두, 코드 컬럼 _cd, Y/N 은 common.d_yn)과
--  감사 컬럼(ins_date/ins_user/upd_date/upd_user) 관례를 그대로 따른다.
--
--  적용 : psql -d dwjedb -f V2__ax_report_extension.sql
-- =====================================================================================

SET search_path TO ax, mes, vec, common, public;

