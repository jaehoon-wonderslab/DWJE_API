COMMENT ON TABLE  ax.tb_rpt_scrap_row                 IS '폐기 보고서 상세 행 — MES 전표 선택분과 수기 추가분';
COMMENT ON COLUMN ax.tb_rpt_scrap_row.kind_cd         IS '폐기 구분 — LOSS(공정 Loss) / DEAD_STOCK(불용재고)';
COMMENT ON COLUMN ax.tb_rpt_scrap_row.origin_type_cd  IS '발생 출처 — MES / MANUAL';
COMMENT ON COLUMN ax.tb_rpt_scrap_row.price_source_cd IS '단가 출처 — MASTER(기준정보) / MANUAL(수기 조정)';

CREATE INDEX IF NOT EXISTS ix_tb_rpt_scrap_row_doc ON ax.tb_rpt_scrap_row (doc_id);

