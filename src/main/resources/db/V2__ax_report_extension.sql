    reason_txt      varchar(200),
    kind_cd         varchar(30)     NOT NULL DEFAULT 'LOSS',
    origin_type_cd  varchar(30)     NOT NULL DEFAULT 'MES',
    qty             numeric(18,6)   NOT NULL DEFAULT 0,
    unit_price      numeric(18,4),
