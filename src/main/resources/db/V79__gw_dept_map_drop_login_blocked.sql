-- =====================================================================================
--  V79 : 그룹웨어 부서 매핑에서 「*_로그인불가」 행 삭제 (2026-10-07)
--
--  V45 가 넣은 가입 제외 행 중 이름이 「_로그인불가」 로 끝나는 2건(퇴사자_로그인불가 · 휴직자_로그인불가)을 지운다
--  (요청: 「*_로그인불가 데이터는 삭제」). 「퇴사자 로그인 불가 x」 는 이름 형태가 달라 남겼다가 V80 에서 지운다.
--
--  [주의 — 동작이 바뀐다]
--  매핑 행이 없는 그룹웨어 부서의 사람은 엔진(GroupwareAxJoinWriter)이 미배정 계정으로 자동 가입시킨다.
--  이 2건을 지우면 그룹웨어에서 이 부서 이름으로 들어오는 사람은 가입 제외가 아니라 미배정으로 가입된다.
--
--  [이 파일이 하는 일]
--  사람이 손댄 행(dept_id 를 정했거나 가입 대상으로 바꾼 행)은 건드리지 않는다 — V45 그대로(dept_id 없음 · join_yn 'N')인 행만 지운다.
--  두 번 실행해도 안전하다.
--
--  [실행]
--  psql -U <user> -d <db> -v ON_ERROR_STOP=1 -f V79__gw_dept_map_drop_login_blocked.sql
--  되돌리기는 rollback/V79__down.sql (V45 의 값으로 다시 넣음).
-- =====================================================================================
BEGIN;
DELETE FROM ax.tb_sys_dept_gw_map
 WHERE gw_dept_nm IN ('퇴사자_로그인불가', '휴직자_로그인불가')
   AND dept_id IS NULL
   AND join_yn = 'N';
COMMIT;
