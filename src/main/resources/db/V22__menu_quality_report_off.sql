-- =====================================================================================
--  V22 : 품질 보고서·양식 관리·폐기 위저드 화면 내리기
--
--  [배경]
--  2026-09-04 사용자 결정.
--
--  1. 품질 보고서(qc-report) — 고객이 준 보고서 자료(Web 프로토타입/보고서 스크린샷 7장)에
--     해당 자료가 없다. 만들기로 한 보고서 6종(아침회의 PRESS·Plating/Coating, 출하계획,
--     제품별 수율, 고객사별 LRR, 폐기 보고서) 어디에도 들어가지 않아 제거한다.
--  2. 보고서 양식 관리(report-forms) — 품질 보고서의 하위 화면이고 그 양식만 다룬다.
--  3. 폐기 보고서 작성 위저드(rpt-scrap-new) — 결재를 앱에서 하지 않기로 했다.
--     "템플릿 및 내용만 채워줄 것이고, 결재선/발행/인쇄는 엑셀로 자료를 받으면
--      로컬파일에서 편집/결재/인쇄 등등을 진행 할 것임" (사용자 지시)
--     5단계 위저드를 접고 폐기 보고서(rpt-scrap) 한 화면으로 다시 짰다.
--
--  [남기는 것]
--  폐기 보고서(rpt-scrap) 는 유지한다 — mes-vouchers 조회로 양식을 채운다.
--  이전 보고서(daily-history) 도 유지한다 — 화면이 안내만 그리기로 했다.
--
--  [물리 삭제하지 않는 이유]
--  V15(비가동 관리)와 같다. 부서별 메뉴 권한이 FK 로 붙어 있어 물리 삭제하면
--  누가 접근 권한을 가졌었는지 기록이 사라진다. 되살릴 때 use_flg 를 'Y' 로
--  돌리면 권한까지 그대로 복원된다. 조회는 이미 use_flg='Y' 로 걸러진다.
--
--  [적용]
--  psql -U dwje_local -d dwjedb -v ON_ERROR_STOP=1 -f V22__menu_quality_report_off.sql
--  두 번 실행해도 안전하다. (이미 'N' 이면 0행)
-- =====================================================================================

UPDATE ax.tb_sys_menu
   SET use_flg = 'N'
 WHERE menu_id IN ('qc-report', 'report-forms', 'rpt-scrap-new')
   AND use_flg = 'Y';
