--  · 공통코드 정합성 목록에 scope_dim_cd 를 다시 넣는다(ALM_SCOPE_DIM 코드는 V73 이 건드리지 않음).
--  · 보관 표는 남긴다(다시 V73 을 적용할 때 덮어씀).
--
--  [옛 엔진 · 옛 API 로 함께 되돌린다]
