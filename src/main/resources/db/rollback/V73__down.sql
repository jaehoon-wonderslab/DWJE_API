--    지정 시각은 NULL 허용, 메시지 틀은 NULL 허용 + 기본 틀). 되살린 컬럼은 표 맨 뒤에 붙는다.
--  · 보관 표 ax.tb_alm_cond_adv_bak 에 있는 조건은 값을 되돌리고, V73 이후 만든 조건은 기본값으로 둔다.
--  · tb_alm_escalation_rule 표를 원래 정의(V35 · V40 주석, 자동 채번 · 단계 유일 · 수신 그룹 FK)로 다시 만들고
