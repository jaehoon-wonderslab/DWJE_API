COMMENT ON COLUMN ax.tb_ai_mask_rule.mask_type_cd IS '처리 방식. 공통코드 그룹 = AI_MASK_TYPE (FULL=마스킹, PARTIAL=부분 마스킹, HASH=해시, DROP=제외)';
COMMENT ON COLUMN ax.tb_ai_mask_rule.customer_id  IS '고객사별 정책인 경우의 대상 고객사. NULL 이면 전체 비공개';

