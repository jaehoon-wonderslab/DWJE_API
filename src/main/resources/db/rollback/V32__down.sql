-- 1. 표 복원 --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ax.tb_ai_mask_rule (
    rule_id      integer          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_nm      varchar(50)      NOT NULL,
    field_key    varchar(30),
    mask_type_cd varchar(30)      NOT NULL,
    customer_id  integer,
    policy_desc  varchar(200),
    use_flg      common.d_yn      NOT NULL DEFAULT 'Y',
    ins_date     timestamptz      NOT NULL DEFAULT now(),
    ins_user     common.d_user_id,
    upd_date     timestamptz      NOT NULL DEFAULT now(),
    upd_user     common.d_user_id,
    CONSTRAINT uq_tb_ai_mask_rule_nm UNIQUE (rule_nm),
    CONSTRAINT tb_ai_mask_rule_customer_id_fkey
        FOREIGN KEY (customer_id) REFERENCES ax.tb_prod_customer(customer_id),
    CONSTRAINT tb_ai_mask_rule_field_key_fkey
        FOREIGN KEY (field_key) REFERENCES ax.tb_sys_data_field(field_key)
);
