--  V79 에서 이름 형태가 달라 남겼던 V45 가입 제외 행 1건을 지운다(요청: 이것도 DB 에서 삭제).
--
--  [주의 — 동작이 바뀐다]
--  매핑 행이 없는 그룹웨어 부서의 사람은 엔진(GroupwareAxJoinWriter)이 미배정 계정으로 자동 가입시킨다.
--  이 행을 지우면 이 부서 이름으로 들어오는 사람은 가입 제외가 아니라 미배정으로 가입된다.
--
--  [이 파일이 하는 일]
--  사람이 손댄 행(dept_id 를 정했거나 가입 대상으로 바꾼 행)은 건드리지 않는다 — V45 그대로(dept_id 없음 · join_yn 'N')인 행만 지운다.
--  두 번 실행해도 안전하다.
--
--  [실행]
--  psql -U <user> -d <db> -v ON_ERROR_STOP=1 -f V80__gw_dept_map_drop_login_blocked_x.sql
--  되돌리기는 rollback/V80__down.sql (V45 의 값으로 다시 넣음).
-- =====================================================================================
BEGIN;
DELETE FROM ax.tb_sys_dept_gw_map
 WHERE gw_dept_nm = '퇴사자 로그인 불가 x'
   AND dept_id IS NULL
   AND join_yn = 'N';
COMMIT;
